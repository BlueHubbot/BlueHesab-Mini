#!/usr/bin/env python3
"""Writes test/fixtures/schema_v1_fixture.sql (T-002, MG-04). Synthetic data.

The fixture is a frozen v1 database: the v1 statements of lib/src/schema.dart
exactly as SQLite will store them, three synthetic accounts/transactions
(one at the 18-digit maximum, one soft-deleted), the schema_migrations row
with the step checksum, and `PRAGMA user_version = 1`.

Run once when v1 is defined; never regenerate it after a release (the test
"v1 steps still produce the frozen fixture schema" depends on that).
Usage: python3 tool/make_fixture.py   (from spike/money)
"""
import hashlib
import pathlib
import re

root = pathlib.Path(__file__).resolve().parent.parent
src = (root / "lib/src/schema.dart").read_text(encoding="utf-8")
block = src.split("const List<String> _v1 = [", 1)[1].split("];", 1)[0]
v1 = re.findall(r"r'''(.*?)'''", block, re.S)
assert len(v1) == 8, len(v1)
checksum = hashlib.sha256("\n;\n".join(v1).encode("utf-8")).hexdigest()

NOW = "2026-10-27T12:00:00.000Z"
WALLET = "کیف‌پول"  # Persian with ZWNJ
BANK = "بانک"
data = [
    "INSERT INTO accounts (id, name, name_norm, kind, currency, opening_balance_minor, "
    f"created_at, updated_at) VALUES ('018f3a00-0000-7000-8000-00000000000a', '{WALLET}', "
    f"'{WALLET.replace(chr(0x200c), '')}', 'cash', 'IRR', '-999999999999999999', '{NOW}', '{NOW}')",
    "INSERT INTO accounts (id, name, name_norm, kind, currency, opening_balance_minor, "
    f"created_at, updated_at) VALUES ('018f3a00-0000-7000-8000-00000000000b', '{BANK}', "
    f"'{BANK}', 'bank', 'IRR', '0', '{NOW}', '{NOW}')",
    "INSERT INTO transactions (id, kind, amount_minor, currency, account_id, to_account_id, "
    "occurred_on, note, created_at, updated_at) VALUES ('018f3a00-0000-7000-8000-000000000001', "
    "'expense', '999999999999999999', 'IRR', '018f3a00-0000-7000-8000-00000000000a', NULL, "
    f"'2026-10-27', NULL, '{NOW}', '{NOW}')",
    "INSERT INTO transactions (id, kind, amount_minor, currency, account_id, to_account_id, "
    "occurred_on, note, created_at, updated_at) VALUES ('018f3a00-0000-7000-8000-000000000002', "
    "'income', '1', 'IRR', '018f3a00-0000-7000-8000-00000000000a', NULL, "
    f"'2026-10-27', 'synthetic', '{NOW}', '{NOW}')",
    "INSERT INTO transactions (id, kind, amount_minor, currency, account_id, to_account_id, "
    "occurred_on, note, created_at, updated_at, deleted_at) VALUES "
    "('018f3a00-0000-7000-8000-000000000003', 'transfer', '500', 'IRR', "
    "'018f3a00-0000-7000-8000-00000000000a', '018f3a00-0000-7000-8000-00000000000b', "
    f"'2026-10-26', NULL, '{NOW}', '{NOW}', '{NOW}')",
    f"INSERT INTO schema_migrations (version, applied_at, checksum) VALUES (1, '{NOW}', '{checksum}')",
    "PRAGMA user_version = 1",
]
header = (
    "-- Frozen schema v1 fixture for T-002 (MG-04). Generated by tool/make_fixture.py.\n"
    "-- Synthetic data only. Do not edit by hand.\n"
)
body = ";\n".join(v1 + data) + ";\n"
out = root / "test/fixtures/schema_v1_fixture.sql"
out.parent.mkdir(parents=True, exist_ok=True)
out.write_text(header + body, encoding="utf-8")
print(f"wrote {out.relative_to(root)} (v1 checksum {checksum})")
