#!/usr/bin/env python3
"""Writes test/fixtures/tz_reference.g.dart for the T-007 spike (SP-04, DT-02).

Independent reference: Python's zoneinfo over the system IANA tz database
(the version is read from tzdata.zi and written into the file). For each zone
it lists every UTC offset change between FIRST and LAST (found by an hourly
scan and a bisection to the second) and two samples per year (15 Jan and
15 Jul, 12:00 UTC). Output is Dart source so the tests run on the VM and in
Chrome. Standard library only; synthetic reference data, no user data.

Usage: python3 -I tool/make_tz_fixture.py [ZONEINFO_DIR]
"""
from __future__ import annotations

import sys
from datetime import datetime, timedelta, timezone
from pathlib import Path
from zoneinfo import ZoneInfo

ZONES = [
    "Asia/Tehran", "Asia/Dubai", "Asia/Kabul", "Europe/Berlin",
    "Europe/London", "America/New_York", "Australia/Sydney",
]
FIRST = datetime(2000, 1, 1, tzinfo=timezone.utc)
LAST = datetime(2036, 1, 1, tzinfo=timezone.utc)


def offset_s(zone: ZoneInfo, t: datetime) -> int:
    return int(t.astimezone(zone).utcoffset().total_seconds())


def transitions(zone: ZoneInfo) -> list[tuple[int, int, int]]:
    out = []
    t = FIRST
    prev = offset_s(zone, t)
    step = timedelta(hours=1)
    while t < LAST:
        n = t + step
        cur = offset_s(zone, n)
        if cur != prev:
            lo, hi = t, n  # offset(lo) == prev, offset(hi) == cur
            while hi - lo > timedelta(seconds=1):
                mid = lo + (hi - lo) / 2
                mid = mid.replace(microsecond=0)
                if offset_s(zone, mid) == prev:
                    lo = mid
                else:
                    hi = mid
            out.append((int(hi.timestamp()) * 1000, prev, cur))
            prev = cur
        t = n
    return out


def main() -> None:
    zi_dir = Path(sys.argv[1] if len(sys.argv) > 1 else "/usr/share/zoneinfo")
    version = (zi_dir / "tzdata.zi").read_text().splitlines()[0].split()[-1]
    lines = [
        "// GENERATED by tool/make_tz_fixture.py - do not edit by hand.",
        f"// Reference: Python {sys.version.split()[0]} zoneinfo, IANA tzdata {version}.",
        f"// Range {FIRST.date()} .. {LAST.date()} (UTC). Synthetic reference data.",
        "",
        "/// IANA tz database version of the reference (README finding T3).",
        f"const String referenceTzdataVersion = '{version}';",
        "",
        "/// Offset changes: (zone, UTC ms of the first instant with the new",
        "/// offset, offset before in seconds, offset after in seconds).",
        "const List<(String, int, int, int)> referenceTransitions = [",
    ]
    samples = []
    for name in ZONES:
        zone = ZoneInfo(name)
        for ms, before, after in transitions(zone):
            lines.append(f"  ('{name}', {ms}, {before}, {after}),")
        for year in range(FIRST.year, LAST.year):
            for month in (1, 7):
                t = datetime(year, month, 15, 12, tzinfo=timezone.utc)
                samples.append((name, int(t.timestamp()) * 1000, offset_s(zone, t)))
    lines.append("];")
    lines += [
        "",
        "/// Samples: (zone, UTC ms, offset in seconds).",
        "const List<(String, int, int)> referenceSamples = [",
    ]
    lines += [f"  ('{n}', {ms}, {off})," for n, ms, off in samples]
    lines.append("];")
    out = Path(__file__).resolve().parent.parent / "test/fixtures/tz_reference.g.dart"
    out.write_text("\n".join(lines) + "\n")
    print(f"wrote {out} ({len(samples)} samples, tzdata {version})")


if __name__ == "__main__":
    main()
